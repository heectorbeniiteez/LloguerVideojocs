    private void btnConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarActionPerformed
        String nom = txtNom.getText().trim();
        String llinatge1 = txtLlinatge1.getText().trim();
        String llinatge2 = txtLlinatge2.getText().trim();
        String dni = txtDni.getText().trim();
        String telefon = txtTelefon.getText().trim();

        // Tots els camps amb * són obligatoris
        if (ValidationAPI.esBuit(nom) || ValidationAPI.esBuit(llinatge1) || ValidationAPI.esBuit(llinatge2)
                || ValidationAPI.esBuit(dni) || ValidationAPI.esBuit(telefon)) {
            mostrarError("Has d'omplir tots els camps obligatoris (*).");
            return;
        }

        // El nom i els llinatges han de començar amb lletra majúscula
        if (!ValidationAPI.comencaAmbMajuscula(nom)) {
            mostrarError("El nom ha de començar amb lletra majúscula.");
            txtNom.requestFocus();
            return;
        }
        if (!ValidationAPI.comencaAmbMajuscula(llinatge1)) {
            mostrarError("El primer llinatge ha de començar amb lletra majúscula.");
            txtLlinatge1.requestFocus();
            return;
        }
        if (!ValidationAPI.comencaAmbMajuscula(llinatge2)) {
            mostrarError("El segon llinatge ha de començar amb lletra majúscula.");
            txtLlinatge2.requestFocus();
            return;
        }

        Usuari nou = new Usuari(nom, llinatge1, llinatge2, dni, telefon);
        try {
            LogicaNegoci.afegirUsuari(nou);
            JOptionPane.showMessageDialog(this, "Usuari " + nou + " creat correctament.");
            dispose();
        } catch (Exception e) {
            mostrarError(e.getMessage());
        }
    }//GEN-LAST:event_btnConfirmarActionPerformed

