    private void prepararPlataforma(JCheckBox check, JSpinner spinner) {
        spinner.setModel(new SpinnerNumberModel(1, 1, 99, 1));
        spinner.setEnabled(false);
        check.addActionListener(e -> spinner.setEnabled(check.isSelected()));
    }

    private void mostrarError(String missatge) {
        JOptionPane.showMessageDialog(this, missatge, "Error", JOptionPane.ERROR_MESSAGE);
    }

    private void confirmar() {
        String nom = jTextField1.getText().trim();

        if (ValidationAPI.esBuit(nom)) {
            mostrarError("Has d'escriure el nom del joc.");
            jTextField1.requestFocus();
            return;
        }
        if (!ValidationAPI.comencaAmbMajuscula(nom)) {
            mostrarError("El nom del joc ha de començar amb lletra majúscula.");
            jTextField1.requestFocus();
            return;
        }
        if (!jCheckBox1.isSelected() && !jCheckBox2.isSelected() && !jCheckBox3.isSelected() && !jCheckBox4.isSelected()) {
            mostrarError("Has de seleccionar com a mínim una plataforma.");
            return;
        }

        Joc nou = new Joc(nom, (String) jComboBox1.getSelectedItem());
        afegirUnitats(nou, jCheckBox1, jSpinner1, "PS5");
        afegirUnitats(nou, jCheckBox2, jSpinner2, "Xbox");
        afegirUnitats(nou, jCheckBox3, jSpinner3, "PC");
        afegirUnitats(nou, jCheckBox4, jSpinner4, "Switch 2");

        try {
            LogicaNegoci.afegirJoc(nou);
            JOptionPane.showMessageDialog(this, "Joc " + nom + " creat correctament.");
            dispose();
        } catch (Exception e) {
            mostrarError(e.getMessage());
        }
    }

    // Només es guarden les unitats de les plataformes marcades
    private void afegirUnitats(Joc joc, JCheckBox check, JSpinner spinner, String plataforma) {
        if (check.isSelected()) {
            joc.setUnitats(plataforma, (Integer) spinner.getValue());
        }
    }

