    // Omple la taula només amb els lloguers actius, del més nou al més antic
    private void carregarTaula() {
        actius = LogicaNegoci.getLloguersActius();
        Collections.reverse(actius);
        taulaActius.setModel(new LloguersTableModel(actius));
        mostrarSeleccionat();
    }

    private Lloguer getSeleccionat() {
        int fila = taulaActius.getSelectedRow();
        if (fila == -1) {
            return null;
        }
        return actius.get(fila);
    }

    // Mostra les dades del lloguer seleccionat i activa el botó només si n'hi ha un
    private void mostrarSeleccionat() {
        Lloguer l = getSeleccionat();
        if (l == null) {
            lblJoc.setText("-");
            lblUsuari.setText("-");
            lblPlataforma.setText("-");
            lblDataInici.setText("-");
            btnRetornar.setEnabled(false);
        } else {
            lblJoc.setText(l.getJoc().getNom());
            lblUsuari.setText(l.getUsuari().toString());
            lblPlataforma.setText(l.getPlataforma());
            lblDataInici.setText(l.getDataInici().format(DateTimeFormatter.ofPattern("dd/MM/yyyy")));
            btnRetornar.setEnabled(true);
        }
    }

